// Run against a separate backend started on port 3010 from .local/verification.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { PDFDocument, PDFName, decodePDFRawStream } from 'pdf-lib';
const base = 'http://127.0.0.1:3010';
const token = 'vol.rahul@fln.org';
async function call(url, body, auth = token) {
  const response = await fetch(base + url, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', ...(auth ? { Authorization: `Bearer ${auth}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  return { status: response.status, data: await response.json() };
}
assert.equal((await call('/api/auth/volunteer-login', { email: 'superadmin@fln.org', password: 'Fln@2026' })).status, 403);
assert.equal((await call('/api/auth/volunteer-login', { email: token, password: 'Fln@2026' })).data.user.role, 'volunteer');
assert.equal((await call('/api/volunteer/papers', undefined, '')).status, 401);
const user = (await call('/api/auth/me')).data.user;
const schoolId = user.assignedSchools[0];
const details = { name: 'Verification Student', age: 6, classGroup: 'Class 1', section: 'A', schoolId, aadharNumber: String(Date.now()).slice(-12), currentLevel: 59 };
assert.equal((await call('/api/students', { ...details, schoolId: 'unassigned-school' })).status, 403);
assert.equal((await call('/api/students', { ...details, age: 'invalid' })).status, 400);
const created = await call('/api/students', details);
assert.equal(created.status, 200);
const student = created.data;
assert.equal(student.currentLevel, 1);
assert.equal(student.currentSubLevel, 0);
assert.equal((await call('/api/students', details)).status, 400);
assert((await call('/api/students')).data.some(s => s.id === student.id));
const paper = await call('/api/volunteer/papers', { studentId: student.id });
assert.equal(paper.status, 200, JSON.stringify(paper.data));
assert.equal(paper.data.level, 1);
const document = await fetch(base + paper.data.pdfUrl);
assert.equal(document.status, 200);
const pdfBytes = Buffer.from(await document.arrayBuffer());
assert.equal(pdfBytes.subarray(0, 4).toString(), '%PDF');
const pdf = await PDFDocument.load(pdfBytes);
assert.equal(pdf.getPageCount(), 1);
const streams = pdf.getPages()[0].node.lookup(PDFName.of('Contents'));
let operators = '';
for (let i = 0; i < streams.size(); i++) operators += Buffer.from(decodePDFRawStream(pdf.context.lookup(streams.get(i))).decode()).toString();
assert.equal((operators.match(/^h$/gm) || []).length, 7, 'Print four corner markers and exactly three text answer boxes.');
assert.equal((operators.match(/^(S|s|B|B\*)$/gm) || []).length, 3, 'Only text questions should have printed answer boxes.');
const templateFile = path.join('backend', 'output', path.basename(paper.data.pdfUrl).replace('.pdf', '.template.json'));
const template = JSON.parse(fs.readFileSync(templateFile, 'utf8')).papers[0];
assert.equal(template.questions.length, 5);
assert.deepEqual(template.questions.map(q => q.questionType), ['text', 'text', 'text', 'multiple_choice', 'match_pair']);
assert.equal(new Set(template.questions.map(q => q.prompt)).size, 5);
assert(template.questions.every(q => q.answerBoxes.length > 0), 'Answer scan regions must remain available.');
const context = await call('/api/ocr/scan/template', { qrText: template.qrPayload });
assert.equal(context.status, 200);
assert(context.data.paper.questionModels.every(q => q.source_level === 1));
const reviews = template.questions.map(q => ({ questionId: q.questionId, finalMark: 'correct', marks: 999, confidence: .8, extractedText: q.answerKey, needsReview: true }));
const save = { studentId: student.id, paperId: template.paperId, testId: template.testId, pageNumber: 1, reviewItems: reviews };
assert.equal((await call('/api/ocr/scan/finalize', { ...save, reviewItems: [] })).status, 400);
assert.equal((await call('/api/ocr/scan/finalize', { ...save, reviewItems: reviews.map(r => ({ ...r, finalMark: null })) })).status, 400);
assert.equal((await call('/api/ocr/scan/finalize', { ...save, testId: 'wrong-test' })).status, 400);
const saved = await call('/api/ocr/scan/finalize', save);
assert.equal(saved.status, 200, JSON.stringify(saved.data));
assert.equal(saved.data.report.score, saved.data.report.totalMarks);
assert(saved.data.report.score < 999);
assert.equal((await call('/api/ocr/scan/finalize', save)).data.alreadySaved, true);
assert.equal((await call(`/api/evaluation/${student.id}/history`)).data.length, 1);
assert.equal((await call(`/api/evaluation/${student.id}/history`, undefined, 'vol.hr_vipin@fln.org')).status, 403);
assert.equal((await call(`/api/evaluation/${student.id}/history`, undefined, '')).status, 401);
assert((await call('/api/volunteer/papers')).data.some(p => p.paperId === template.paperId));
fs.writeFileSync('.local/verification/result.json', JSON.stringify({ studentId: student.id, reportId: saved.data.report.id, paperId: template.paperId, pdfUrl: paper.data.pdfUrl, templateFile }, null, 2));
console.log('PASS: volunteer login, assigned-school access, Level 1 registration, duplicate rejection, level-matched QR PDF generation, review validation, server-calculated scores, idempotent saves, saved history, and paper retrieval.');
